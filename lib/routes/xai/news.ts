import { load } from 'cheerio';

import type { DataItem, Route } from '@/types';
import { unlockWebsite } from '@/utils/bright-data-unlocker';
import { parseDate } from '@/utils/parse-date';

const link = 'https://x.ai/news';

export const parsePosts = (html: string): DataItem[] => {
    const $ = load(html);
    const items = new Map<string, DataItem>();
    for (const element of $('a[href^="/news/"]').toArray()) {
        const card = $(element);
        const heading = card.find('h1, h2, h3, h4').first();
        const title = heading.text();
        const url = new URL(card.attr('href')!, link).href;
        const datetime = card.find('time[datetime]').first().attr('datetime');
        const date =
            datetime ||
            card
                .find('p, div')
                .toArray()
                .map((node) => $(node).text())
                .find((text) => /^[A-Z][a-z]{2} \d{1,2}, \d{4}$/.test(text));
        if (!title || !date || items.has(url)) {
            continue;
        }
        const pubDate = parseDate(`${date} +0000`, datetime ? 'YYYY-MM-DD ZZ' : 'MMM D, YYYY ZZ');
        if (Number.isNaN(pubDate.getTime())) {
            continue;
        }
        const image = card.find('img').first().attr('src');
        items.set(url, {
            title,
            link: url,
            pubDate,
            description: heading.next('p').html() || undefined,
            image: image ? new URL(image, link).href : undefined,
        });
    }
    if (!items.size) {
        throw new Error('No xAI news articles found');
    }
    return [...items.values()].toSorted((a, b) => new Date(b.pubDate!).getTime() - new Date(a.pubDate!).getTime());
};

export const handler = async () => ({
    title: 'SpaceXSI News',
    link,
    description: 'Research, product and company updates from SpaceXSI',
    item: parsePosts(await unlockWebsite(link)),
});

export const route: Route = {
    path: '/news',
    categories: ['programming'],
    example: '/xai/news',
    features: {
        requireConfig: [
            { name: 'BRIGHTDATA_API_KEY', description: 'Bright Data API key for web unlocker' },
            { name: 'BRIGHTDATA_UNLOCKER_ZONE', description: 'Bright Data zone identifier for web unlocker' },
        ],
        antiCrawler: true,
    },
    name: 'News',
    maintainers: ['Generated by Claude'],
    handler,
};
